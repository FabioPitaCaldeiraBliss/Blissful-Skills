def corner(L):
    if L.get("type") == "ellipse":
        return min(L.get("w", 0), L.get("h", 0)) / 2
    r = L.get("radius", 0)
    return r[0] if isinstance(r, list) else r


def m_shape_morph(P, m, at):
    chain = m.get("chain") or [m["target"], m["to"]]
    d = m.get("d", 0.8)
    for a, b in zip(chain, chain[1:]):
        A, B = P.layer(a), P.layer(b)
        ax, ay, aw, ah = P.box(a)
        bx, by, bw, bh = P.box(b)
        sx, sy = (bw / aw if aw else 1), (bh / ah if ah else 1)
        dx, dy = (bx + bw / 2) - (ax + aw / 2), (by + bh / 2) - (ay + ah / 2)
        s = max((sx + sy) / 2, 0.01)
        P.tw(a, {"x": 0, "y": 0, "scaleX": 1, "scaleY": 1, "borderRadius": f"{corner(A)}px"},
             {"x": round(dx, 1), "y": round(dy, 1), "scaleX": round(sx, 4), "scaleY": round(sy, 4),
              "borderRadius": f"{round(corner(B) / s, 1)}px"}, at, d, ease(m.get("ease"), "ease in-out"))
        P.tw(a, {"opacity": P.opacity(a)}, {"opacity": 0}, at + d * 0.7, d * 0.3, "none")
        P.tw(b, {"opacity": 0}, {"opacity": P.opacity(b)}, at + d * 0.7, d * 0.3, "none")
        at += d + m.get("hold", 0.6)


