def m_tap(P, m, at):
    P.touch = True
    x, y, w, h = P.box(m["target"])
    tx, ty = round(x + w / 2 + m.get("dx", 0)), round(y + h / 2 + m.get("dy", 0))
    dot, ring = f"#{P.pid}-touch", f"#{P.pid}-ripple"
    start = getattr(P, "touch_at", None) or [tx + 160, ty + 220]
    P.tw(dot, {"x": start[0], "y": start[1], "opacity": 0, "scale": 1}, {"x": tx, "y": ty, "opacity": 1, "scale": 1}, at - 0.5, 0.5, "power3.out")
    P.tw(dot, {"scale": 1}, {"scale": 0.82, "yoyo": True, "repeat": 1}, at, 0.12, "power2.inOut")
    P.tw(ring, {"opacity": 0}, {"opacity": 0.8}, at + 0.04, 0.01, "none")
    P.tw(ring, {"x": tx, "y": ty, "scale": 0.4}, {"x": tx, "y": ty, "scale": 2.2}, at + 0.05, 0.6, "power2.out")
    P.tw(ring, {"opacity": 0.8}, {"opacity": 0}, at + 0.06, 0.59, "power2.out")
    P.tw(m["target"], {"scale": 1}, {"scale": 0.96, "yoyo": True, "repeat": 1}, at, 0.12, "power2.inOut")
    P.tw(dot, {"opacity": 1}, {"opacity": 0}, at + 0.45, 0.3, "none")
    P.touch_at = [tx, ty]


def m_swap(P, m, at, scale=None, d=0.5):
    """screen-swap, content-swap, background-swap, state-change: cross-fade from one set to the next."""
    if "state" in m and "target" not in m:
        n = int(m["state"])
        to = [f"{L['name']}@{n}" for L in P.by_key.values() if L["state"] == n and not L.get("_child")]
        frm = [L["name"] for L in P.by_key.values() if L["state"] == 1 and (L["name"], n) in P.by_key]
    else:
        frm, to = as_list(m.get("target", [])), as_list(m["to"])
    d = m.get("d", d)
    e = ease(m.get("ease"), "ease in-out")
    for t in frm:
        P.tw(t, {"opacity": P.opacity(t)}, {"opacity": 0}, at, d, e)
    for t in to:
        f, o = {"opacity": 0}, {"opacity": P.opacity(t)}
        if scale:
            f["scale"], o["scale"] = scale, 1
        P.tw(t, f, o, at, d, e)


