def stagger(n, st, cap=0.6):
    return min(st, cap / (n - 1)) if n > 1 else st


def m_enter(P, m, at, d=0.6, e="expo out", frm=None):
    frm = dict(m.get("from") or frm or {"y": m.get("y", 40)})
    for t in as_list(m["target"]):
        to = {k: (1 if k in ("scale", "scaleX", "scaleY") else 0) for k in frm}
        frm["opacity"], to["opacity"] = 0, P.opacity(t)
        if "rotationY" in frm:
            frm["transformPerspective"] = to["transformPerspective"] = 1400
        if "origin" in m:
            frm["transformOrigin"] = to["transformOrigin"] = m["origin"]
        P.tw(t, frm, to, at, m.get("d", d), ease(m.get("ease"), e))
        at += m.get("stagger", 0)


def m_exit(P, m, at, d=0.4, e="expo in", to=None):
    to = dict(to or {"y": m.get("y", -30)})
    for t in as_list(m["target"]):
        frm = {k: (1 if k in ("scale", "scaleX", "scaleY") else 0) for k in to}
        frm["opacity"], to["opacity"] = P.opacity(t), 0
        P.tw(t, frm, dict(to), at, m.get("d", d), ease(m.get("ease"), e))


def m_fade(P, m, at):
    for t in as_list(m["target"]):
        a, b = (0, P.opacity(t)) if m.get("dir", "in") == "in" else (P.opacity(t), 0)
        P.tw(t, {"opacity": a}, {"opacity": b}, at, m.get("d", 0.5), ease(m.get("ease"), "ease in-out"))


def split(P, ref, mode):
    P.splits[P.sel(ref)] = mode
    return P.sel(ref) + (" .w" if mode == "words" else " .ch")


def m_phrase_in(P, m, at):
    t = m["target"]
    n = len(P.layer(t).get("text", "").split())
    st = stagger(n, m.get("stagger", 0.08), 0.8)
    P.tw(split(P, t, "words"), {"opacity": 0, "y": m.get("y", 24)}, {"opacity": 1, "y": 0, "stagger": st},
         at, m.get("d", 0.6), ease(m.get("ease"), "expo out"))
    if P.opacity(t) != 1 or P.layer(t).get("state", 1) > 1:
        P.tw(t, {"opacity": 0}, {"opacity": P.opacity(t)}, at, 0.01, "none")


def m_phrase_out(P, m, at):
    t = m["target"]
    n = len(P.layer(t).get("text", "").split())
    P.tw(split(P, t, "words"), {"opacity": 1, "y": 0}, {"opacity": 0, "y": -m.get("y", 16), "stagger": stagger(n, 0.04, 0.3)},
         at, m.get("d", 0.4), ease(m.get("ease"), "expo in"))


def m_phrase_swap(P, m, at):
    m_phrase_out(P, dict(m, d=0.4), at)
    m_phrase_in(P, dict(m, target=m["to"], d=0.6), at + 0.3)


