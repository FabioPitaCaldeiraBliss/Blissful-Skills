def m_push_in(P, m, at):
    x, y, w, h = P.box(m["target"])
    fill = m.get("fill", 0.8)
    s = min(P.W * fill / w, P.H * fill / h) if w and h else 1.5
    s = min(s, m.get("max", 4))
    cx, cy = x + w / 2, y + h / 2
    camera(P, [round(P.W / 2 - s * cx, 1), round(P.H / 2 - s * cy, 1), round(s, 4)], at, m.get("d", 1.2), ease(m.get("ease"), "ease in-out"))


def m_pull_out(P, m, at):
    camera(P, [0, 0, 1], at, m.get("d", 1.2), ease(m.get("ease"), "ease in-out"))


