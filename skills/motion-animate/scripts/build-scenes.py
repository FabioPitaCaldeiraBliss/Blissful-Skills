def m_photo_mosaic(P, m, at):
    tiles = as_list(m["target"])
    st = stagger(len(tiles), m.get("stagger", 0.06), 0.8)
    for i, t in enumerate(tiles):
        P.tw(t, {"opacity": 0, "scale": 0.9}, {"opacity": P.opacity(t), "scale": 1}, at + i * st, m.get("d", 0.4), "expo.out")


def m_dissolve(P, m, at):
    a, b = (0, 1) if m.get("dir", "out") == "in" else (1, 0)
    P.tw(f"#{P.pid}-camera", {"opacity": a}, {"opacity": b}, at, m.get("d", 0.6), "power2.inOut")


def loop(P, m, at, cycle):
    end = m.get("until", P.dur)
    reps = max(int((end - at) / cycle * 2) - 1, 0)
    return reps


def m_glow_drift(P, m, at):
    cycle = m.get("d", 8) / 2
    for t in as_list(m["target"]):
        P.tw(t, {"x": 0, "y": 0}, {"x": m.get("x", 60), "y": m.get("y", -40), "yoyo": True, "repeat": loop(P, m, at, cycle * 2)}, at, cycle, "sine.inOut")


def m_breathe(P, m, at):
    cycle = m.get("d", 3) / 2
    for t in as_list(m["target"]):
        P.tw(t, {"scale": 1}, {"scale": 1 + m.get("amount", 0.02), "yoyo": True, "repeat": loop(P, m, at, cycle * 2)}, at, cycle, "sine.inOut")


