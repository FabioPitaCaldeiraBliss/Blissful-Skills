def m_success_burst(P, m, at):
    t = m["target"]
    x, y, w, h = P.box(t)
    n = m.get("particles", 8)
    col = m.get("color") or P.piece.get("accent", "#ffffff")
    P.bursts[t] = (x + w / 2, y + h / 2, n, col)
    P.tw(t, {"opacity": 0, "scale": 0.6}, {"opacity": P.opacity(t), "scale": 1}, at, m.get("d", 0.7), "back.out(1.7)")
    r = max(w, h) / 2 + m.get("spread", 90)
    for i in range(n):
        a = 2 * math.pi * i / n - math.pi / 2
        p = f"#{P.sel(t)[1:]}-p{i}"
        P.tw(p, {"x": 0, "y": 0, "scale": 1}, {"x": round(r * math.cos(a)), "y": round(r * math.sin(a)), "scale": 0.4}, at + 0.1, 0.7, "expo.out")
        P.tw(p, {"opacity": 0}, {"opacity": 1}, at + 0.1, 0.05, "none")
        P.tw(p, {"opacity": 1}, {"opacity": 0}, at + 0.4, 0.4, "none")


def m_mask_reveal(P, m, at):
    """masked-video and photo windows: grow a rounded window from a slit or a point."""
    r = m.get("radius", corner(P.layer(m["target"])) if m["target"] not in P.groups else 0)
