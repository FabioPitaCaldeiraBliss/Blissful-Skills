def m_chat_stack(P, m, at):
    bubbles = as_list(m["target"])
    gap = m.get("gap", 0.75)
    bottoms = [P.box(b)[1] + P.box(b)[3] for b in bubbles]
    last = bottoms[-1]
    shown = []
    for k, b in enumerate(bubbles):
        t = at + k * gap
        off = round(last - bottoms[k])
        for j in shown:
            prev = round(last - bottoms[k - 1])
            P.tw(j, {"y": prev}, {"y": off}, t, 0.4, "power2.out")
        P.tw(b, {"opacity": 0, "y": off + 30, "scale": 0.9, "transformOrigin": m.get("origin", "0% 100%")},
             {"opacity": P.opacity(b), "y": off, "scale": 1, "transformOrigin": m.get("origin", "0% 100%")}, t, m.get("d", 0.4), "expo.out")
        shown.append(b)


