#!/usr/bin/env python3
"""Build HyperFrames scene compositions from scenes.json (the frames read back from Figma plus
the moves from STORYBOARD.md), and optionally the index.html for a render scope.

Usage:
  build-scenes.py PROJECT [--scenes scenes.json] [--only 01,03] [--force 03] [--scope all|01,03|02-05]

Writes PROJECT/compositions/panel-NN.html per panel. A panel whose file was edited by hand since
it was generated is skipped and reported, unless named in --force. With --scope, also writes
PROJECT/index.html mounting the chosen panels back to back.
Standard library only. Format of scenes.json: references/scenes-json.md.
Exits 0 on success, 1 on a scenes.json error, 2 when a file is missing.
"""
import argparse, hashlib, html, json, math, os, re, sys

EASES = {"expo out": "expo.out", "expo in": "expo.in", "ease in-out": "power2.inOut",
         "sine": "sine.inOut", "linear": "none", "spring": "back.out(1.6)"}
WEIGHTS = {"thin": 100, "light": 300, "regular": 400, "medium": 500, "semibold": 600, "bold": 700, "black": 900}
STAMP = "<!-- generated by build-scenes.py · sha1:{} -->"
WARN = []


def slug(s):
    s = s.split(" / ", 1)[-1]
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "layer"


def ease(v, default):
    v = v or default
    return EASES.get(v, v)


def js(v):
    return json.dumps(v, separators=(",", ":"))


# ------------------------------------------------------------------ geometry

class Panel:
    def __init__(self, spec, piece):
        self.spec, self.piece = spec, piece
        self.num = spec["id"]
        self.pid = "p" + self.num
        self.W, self.H = piece["format"]["width"], piece["format"]["height"]
        self.dur = float(spec["duration"])
        self.layers, self.by_key, self.ids = [], {}, set()
        for L in spec["layers"]:
            self._index(L, 0, 0)
        self.groups = spec.get("groups", {})
        self.member = {}
        for g, G in self.groups.items():
            for m in G["members"]:
                self.member[self._key(m)] = g
        self.tweens, self.raw, self.splits, self.extra = [], [], {}, []
        self.stroke_svg, self.swaps, self.bursts, self.touch = set(), {}, {}, False
        self.cam = [0.0, 0.0, 1.0]

    def _key(self, ref):
        name, _, st = ref.partition("@")
        return (name, int(st or 1))

    def _index(self, L, ox, oy):
        L.setdefault("state", 1)
        key = (L["name"], L["state"])
        base = f"{self.pid}-{slug(L['name'])}" + (f"--s{L['state']}" if L["state"] > 1 else "")
        eid, n = base, 2
        while eid in self.ids:
            eid, n = f"{base}-{n}", n + 1
        self.ids.add(eid)
        L["_id"], L["_abs"] = eid, (ox + L.get("x", 0), oy + L.get("y", 0))
        if key not in self.by_key:
            self.by_key[key] = L
        self.layers.append(L) if ox == 0 and oy == 0 and not L.get("_child") else None
        for C in L.get("children", []):
            C["_child"] = True
            self._index(C, L["_abs"][0], L["_abs"][1])

    def layer(self, ref):
        k = self._key(ref)
        if k not in self.by_key:
            raise SystemExit(f"panel {self.num}: no layer named '{ref}'")
        return self.by_key[k]

    def sel(self, ref):
        if ref in self.groups:
            return f"#{self.pid}-g-{slug(ref)}"
        return "#" + self.layer(ref)["_id"]

    def box(self, ref):
        if ref in self.groups:
            bs = [self.box(m) for m in self.groups[ref]["members"]]
            x0, y0 = min(b[0] for b in bs), min(b[1] for b in bs)
            x1, y1 = max(b[0] + b[2] for b in bs), max(b[1] + b[3] for b in bs)
            return (x0, y0, x1 - x0, y1 - y0)
        L = self.layer(ref)
        return (L["_abs"][0], L["_abs"][1], L.get("w", 0), L.get("h", 0))

    def opacity(self, ref):
        if ref in self.groups:
            return 1
        return self.layer(ref).get("opacity", 1)

    # tweens are collected, then sorted by time so the first tween per property owns t=0
    def tw(self, ref_or_sel, frm, to, at, d, e, init=True):
        """init=False: the from state is whatever earlier moves left, so it never sets the t=0 state."""
        sel = ref_or_sel if ref_or_sel.startswith("#") else self.sel(ref_or_sel)
        self.tweens.append(dict(sel=sel, frm=frm, to=to, at=round(at, 3), d=round(d, 3), e=e, init=init))


