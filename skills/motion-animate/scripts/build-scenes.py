def m_word_swap(P, m, at):
    """Two full lines (the frame's two states): the words that differ slide out and in, the shared words cross-fade."""
    A, B = P.layer(m["target"]), P.layer(m["to"])
    wa, wb = A.get("text", "").split(" "), B.get("text", "").split(" ")
    pre = 0
    while pre < min(len(wa), len(wb)) and wa[pre] == wb[pre]:
        pre += 1
    suf = 0
    while suf < min(len(wa), len(wb)) - pre and wa[-1 - suf] == wb[-1 - suf]:
        suf += 1
    P.swaps[A["_id"]] = (pre, suf)
    P.swaps[B["_id"]] = (pre, suf)
    d = m.get("d", 0.5)
    a, b = "#" + A["_id"], "#" + B["_id"]
    P.tw(b, {"opacity": 0}, {"opacity": P.opacity(m["to"])}, at, 0.01, "none")
    P.tw(a + " .wd", {"opacity": 1, "y": 0}, {"opacity": 0, "y": "-0.6em"}, at, d * 0.6, "expo.in", init=False)
    P.tw(b + " .wd", {"opacity": 0, "y": "0.6em"}, {"opacity": 1, "y": 0}, at + d * 0.4, d * 0.8, "expo.out")
    P.tw(a + " .wc", {"opacity": 1}, {"opacity": 0}, at + d * 0.3, d * 0.7, "power2.inOut", init=False)
    P.tw(b + " .wc", {"opacity": 0}, {"opacity": 1}, at + d * 0.3, d * 0.7, "power2.inOut")


