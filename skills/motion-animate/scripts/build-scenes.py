def css_fill(f):
    if f is None:
        return "transparent"
    if isinstance(f, str):
        return f
    stops = ",".join(f"{c} {round(p * 100)}%" for p, c in f["stops"])
    if f.get("type") == "radial":
        return f"radial-gradient(circle at {f.get('at', '50% 50%')},{stops})"
    return f"linear-gradient({f.get('angle', 90)}deg,{stops})"


def solid(f):
    if isinstance(f, dict):
        return f["stops"][0][1]
    return f or "none"


def radius_css(r):
    if isinstance(r, list):
        return " ".join(f"{v}px" for v in r)
    return f"{r}px" if r else ""


def text_html(P, L):
    t = L.get("text", "")
    if L["_id"] in P.swaps:
        pre, suf = P.swaps[L["_id"]]
        words = t.split(" ")
        cls = ["wc" if i < pre or i >= len(words) - suf else "wd" for i in range(len(words))]
        return " ".join(f'<span class="{c}" style="display:inline-block">{html.escape(w)}</span>' for c, w in zip(cls, words))
    cuts = {0, len(t)}
    acc = L.get("accents", [])
    for a, b, _ in acc:
        cuts |= {a, b}
    cuts = sorted(c for c in cuts if 0 <= c <= len(t))
    out = []
    for a, b in zip(cuts, cuts[1:]):
        seg = html.escape(t[a:b])
        for i, (x, y, col) in enumerate(acc):
            if x <= a and b <= y:
                out.append(f'<span id="{L["_id"]}-a{i}" style="color:{col}">{seg}</span>')
                break
        else:
            out.append(seg)
    return "".join(out)


def style_box(L, x, y):
    s = f"position:absolute;left:{x}px;top:{y}px;width:{L.get('w', 0)}px;height:{L.get('h', 0)}px;"
    hidden = L.get("state", 1) > 1 and not L.get("_group_hides")
    if L.get("opacity", 1) != 1 or hidden:
        s += f"opacity:{0 if hidden else L['opacity']};"
    if L.get("blur"):
        s += f"filter:blur({L['blur'] / 2}px);"
    if L.get("rotation"):
        s += f"transform:rotate({L['rotation']}deg);"
    sh = L.get("shadow")
    if sh:
        s += f"box-shadow:{sh if isinstance(sh, str) else '{}px {}px {}px {}'.format(sh.get('x', 0), sh.get('y', 0), sh.get('blur', 0), sh.get('color', 'rgba(0,0,0,.2)'))};"
    return s


def render(P, L, ox=0, oy=0):
    x, y = L.get("x", 0), L.get("y", 0)
    eid, k = L["_id"], L.get("type", "rect")
    base = style_box(L, x, y)
    allow = " data-layout-allow-overlap" if L.get("state", 1) > 1 or L.get("allow_overlap") else ""
    if L.get("_child") or L.get("allow_overflow"):
        allow += " data-layout-allow-overflow"
    if k == "text":
        lh = L.get("lineHeight", 1.2)
        lh = f"{lh}px" if lh > 4 else lh
        fw = L.get("weight", 400)
        fw = WEIGHTS.get(str(fw).lower(), fw)
        s = (base.replace(f"height:{L.get('h', 0)}px;", "") +
             f"font-family:'{L.get('font', P.piece.get('font', 'sans-serif'))}',sans-serif;font-size:{L['size']}px;font-weight:{fw};"
             f"color:{L.get('color', '#000')};text-align:{L.get('align', 'left').lower()};letter-spacing:{L.get('tracking', 0)}em;"
             f"line-height:{lh};white-space:pre-line;")
        if L.get("tabular"):
            s += "font-variant-numeric:tabular-nums;"
        return f'<div id="{eid}"{allow} style="{s}">{text_html(P, L)}</div>'
    if eid in P.stroke_svg or k == "vector":
        stv = L.get("stroke") or {}
        sw = stv.get("width", 0)
        attrs = f'fill="{solid(L.get("fill")) if L.get("fill") else "none"}"'
        if stv:
            attrs += f' stroke="{stv["color"]}" stroke-width="{sw}" stroke-linecap="round"'
        if eid in P.stroke_svg:
            attrs += ' class="st" pathLength="1" stroke-dasharray="1"'
        w, h = L.get("w", 0), L.get("h", 0)
        if k == "ellipse":
            shape = f'<ellipse cx="{w / 2}" cy="{h / 2}" rx="{max(w - sw, 0) / 2}" ry="{max(h - sw, 0) / 2}" {attrs}/>'
        elif k == "vector":
            shape = "".join(f'<path d="{d}" {attrs}/>' for d in as_list(L["paths"]))
        else:
            shape = f'<rect x="{sw / 2}" y="{sw / 2}" width="{max(w - sw, 0)}" height="{max(h - sw, 0)}" rx="{corner(L)}" {attrs}/>'
        return (f'<svg id="{eid}"{allow} style="{base}overflow:visible" viewBox="0 0 {w} {h}" '
                f'xmlns="http://www.w3.org/2000/svg">{shape}</svg>')
    s = base + "box-sizing:border-box;"
    if k == "image":
        fit = {"fill": "100% 100%", "cover": "cover", "contain": "contain"}[L.get("fit", "fill")]
        s += f"background:url('{L['src']}') center/{fit} no-repeat;"
    elif k == "video":
        s += f"object-fit:{L.get('fit', 'cover')};"
        r = radius_css(L.get("radius", 0))
        s += f"border-radius:{r};" if r else ""
        return (f'<video id="{eid}" class="clip" src="{L["src"]}" muted playsinline data-start="{L.get("start", 0)}" '
                f'data-duration="{L.get("duration", P.dur)}" data-track-index="{L.get("track", 1)}" style="{s}"></video>')
    else:
        s += f"background:{css_fill(L.get('fill'))};"
    if k == "ellipse":
        s += "border-radius:50%;"
    elif L.get("radius"):
        s += f"border-radius:{radius_css(L['radius'])};"
    if L.get("stroke"):
        st = L["stroke"]
        s += f"border:{st['width']}px {'dashed' if st.get('dashed') else 'solid'} {st['color']};"
    if L.get("clip") or L.get("children"):
        s += "overflow:hidden;"
    inner = "".join(render(P, C) for C in L.get("children", []))
    return f'<div id="{eid}"{allow} style="{s}">{inner}</div>'


